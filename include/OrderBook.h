#pragma once

// ============================================================================
// OrderBook.h – Manages the bids and asks for a single stock symbol
//
// LEARNING NOTES (C++ Data Structures):
// 1. std::map: A self-balancing binary search tree (Red-Black Tree, like Java TreeMap).
//    Keys are ALWAYS kept sorted.
//    - For asks: std::map<Price, ...> sorts ascending (lowest price first = best ask).
//    - For bids: std::map<Price, ..., std::greater<Price>> sorts descending
//      (highest price first = best bid).
// 2. std::deque: "Double-ended queue" (like Java ArrayDeque).
//    At any given price level, orders are stored in a deque so the oldest order
//    is at the front (FIFO = Time Priority).
// 3. std::optional: Similar to Java's Optional<T>. Represents a value that may
//    or may not be present (e.g., best bid price when the book is empty).
// ============================================================================

#include "Order.h"
#include "Trade.h"
#include <string>
#include <map>
#include <deque>
#include <vector>
#include <unordered_map>
#include <optional>

class OrderBook {
public:
    explicit OrderBook(std::string symbol);

    // Add a new order to the book and return any trades generated by matching
    std::vector<Trade> addOrder(Order order);

    // Cancel an order by its ID (returns true if found and cancelled)
    bool cancelOrder(OrderId orderId);

    // Inspect best available prices
    std::optional<Price> getBestBid() const;
    std::optional<Price> getBestAsk() const;

    // Print the current order book ladder to standard output
    void printBook() const;

    // Getters
    const std::string& getSymbol() const { return symbol_; }
    const std::vector<Trade>& getTradeHistory() const { return tradeHistory_; }

private:
    std::string symbol_;

    // Bids: Sorted HIGHEST price first (std::greater)
    std::map<Price, std::deque<Order>, std::greater<Price>> bids_;

    // Asks: Sorted LOWEST price first (default std::less)
    std::map<Price, std::deque<Order>> asks_;

    // Quick lookup: maps OrderId -> {Side, Price} for O(1) order location during cancel
    struct OrderLocation {
        Side side;
        Price price;
    };
    std::unordered_map<OrderId, OrderLocation> orderLookup_;

    // History of all trades executed in this book
    std::vector<Trade> tradeHistory_;

    // Internal matching helper methods
    std::vector<Trade> matchBuyOrder(Order& buyOrder);
    std::vector<Trade> matchSellOrder(Order& sellOrder);
};
